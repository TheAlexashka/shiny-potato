type Curve = [number, number, number, number, number, number, number, number];

export interface Surface {
  d: string;
  strands?: string[];
  highlights?: string[];
  shadows?: string[];
  part?: string;
  transform?: string;
  /** аксессуар (лента и т.п.) — красится своей переменной, а не цветом волос */
  accessory?: boolean;
}

interface HairDesign {
  front: Surface[];
  back: Surface[];
}

function bundle(a: Curve, b: Curve, count = 22): string[] {
  return Array.from({ length: count }, (_, i) => {
    const t = i / Math.max(1, count - 1);
    const p = a.map((v, j) => +(v + (b[j] - v) * t).toFixed(2));
    return `M${p[0]} ${p[1]} C${p[2]} ${p[3]} ${p[4]} ${p[5]} ${p[6]} ${p[7]}`;
  });
}

