function HairSurface({ surface, uid, ribbonColor }: { surface: Surface; uid: string; ribbonColor?: string }) {
  const base = surface.accessory ? (ribbonColor ?? 'var(--ribbon, #8b2635)') : 'var(--hair, #4a3222)';
  const mixDark = (p: number) => `color-mix(in srgb, ${base} ${p}%, black)`;
  const mixLight = (p: number) => `color-mix(in srgb, ${base} ${p}%, white)`;
  return (
    <g transform={surface.transform} data-accessory={surface.accessory ? 'ribbon' : undefined}>
      <defs>
        <clipPath id={`${uid}-clip`} clipPathUnits="userSpaceOnUse"><path d={surface.d} /></clipPath>
        <linearGradient id={`${uid}-volume`} x1="0" y1="0" x2="0.9" y2="0.65">
          <stop stopColor={mixDark(45)} stopOpacity={0.42} />
          <stop offset="0.26" stopColor={mixLight(62)} stopOpacity={0.28} />
          <stop offset="0.42" stopColor={mixLight(45)} stopOpacity={surface.accessory ? 0.55 : 0.34} />
          <stop offset="0.58" stopColor={mixLight(82)} stopOpacity={0.1} />
          <stop offset="0.82" stopColor={mixDark(68)} stopOpacity={0.3} />
          <stop offset="1" stopColor={mixDark(42)} stopOpacity={0.52} />
        </linearGradient>
      </defs>
      <path d={surface.d} fill={base} stroke={mixDark(62)} strokeWidth={0.9} strokeLinejoin="round" />
      <g clipPath={`url(#${uid}-clip)`}>
        <path d={surface.d} fill={`url(#${uid}-volume)`} />
        {surface.shadows?.map((d, i) => <path key={`s-${i}`} d={d} fill={mixDark(45)} opacity={0.4} />)}
        {surface.highlights?.map((d, i) => <path key={`h-${i}`} d={d} fill={mixLight(40)} opacity={surface.accessory ? 0.55 : 0.38} />)}
        <g fill="none" strokeLinecap="round">
          {surface.strands?.map((d, i) => (
            <path
              key={i}
              d={d}
              stroke={i % 3 === 0 ? mixLight(45) : mixDark(62)}
              strokeWidth={i % 3 === 0 ? 0.3 : 0.44}
              opacity={i % 3 === 0 ? 0.5 : 0.42}
            />
          ))}
          {surface.part && (
            <>
              <path d={surface.part} stroke={mixDark(50)} strokeWidth={1.7} opacity={0.65} />
              <path d={surface.part} stroke={mixLight(55)} strokeWidth={0.57} opacity={0.8} />
            </>
          )}
        </g>
      </g>
    </g>
  );
}

export const Hair = memo(function Hair({
  styleId,
  layer = 'front',
  face,
}: {
  styleId: string;
  layer?: 'front' | 'back';
  face?: FaceSel;
}) {
  const uid = `hair-${useId().replace(/:/g, '')}`;
  const design = DESIGNS[styleId] ?? waves;
  const surfaces = design[layer];
  if (!surfaces?.length) return null;

  const isFront = layer === 'front';
  const scaleW = ((isFront ? face?.hairFrontWidth : face?.hairBackWidth) ?? 100) / 100;
  const scaleH = ((isFront ? face?.hairFrontHeight : face?.hairBackHeight) ?? 100) / 100;
  const ribbonColor = face?.ribbonColor;

  return (
    <g
      data-hair-style={styleId}
      data-hair-layer={layer}
      className="hair-art"
      transform={`translate(150 64) scale(${scaleW.toFixed(3)} ${scaleH.toFixed(3)}) translate(-150 -64)`}
    >
      {surfaces.map((surface, i) => (
        <HairSurface key={i} surface={surface} uid={`${uid}-${i}`} ribbonColor={ribbonColor} />
      ))}
    </g>
  );
});
