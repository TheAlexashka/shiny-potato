function realisticBraid(cx: number, startY: number, length: number, w: number, dxCurve = 0): Surface {
  const steps = Math.max(5, Math.round(length / 14));
  const stepH = length / steps;
  const strands: string[] = [];
  const highlights: string[] = [];
  const leftPts: [number, number][] = [];
  const rightPts: [number, number][] = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const y = startY + i * stepH;
    const xMid = cx + dxCurve * Math.sin(t * Math.PI);
    const curW = w * (1 - t * 0.45);
    leftPts.push([xMid - curW, y]);
    rightPts.push([xMid + curW, y]);
    if (i < steps) {
      const ym = y + stepH * 0.5;
      const yNext = y + stepH;
      if (i % 2 === 0) {
        strands.push(`M${xMid - curW} ${y} C${xMid - curW * 0.3} ${ym + 2} ${xMid} ${ym + 3} ${xMid + curW * 0.8} ${yNext}`);
        strands.push(`M${xMid - curW * 0.7} ${y + 2} C${xMid} ${ym} ${xMid + curW * 0.5} ${yNext - 1} ${xMid + curW * 0.6} ${yNext}`);
        highlights.push(`M${xMid - curW * 0.8} ${y + 1} Q${xMid - curW * 0.2} ${ym} ${xMid} ${ym + 2}`);
      } else {
        strands.push(`M${xMid + curW} ${y} C${xMid + curW * 0.3} ${ym + 2} ${xMid} ${ym + 3} ${xMid - curW * 0.8} ${yNext}`);
        strands.push(`M${xMid + curW * 0.7} ${y + 2} C${xMid} ${ym} ${xMid - curW * 0.5} ${yNext - 1} ${xMid - curW * 0.6} ${yNext}`);
        highlights.push(`M${xMid + curW * 0.8} ${y + 1} Q${xMid + curW * 0.2} ${ym} ${xMid} ${ym + 2}`);
      }
    }
  }
  let dPath = `M${leftPts[0][0]} ${leftPts[0][1]} `;
  for (let i = 1; i < leftPts.length; i++) {
    const prev = leftPts[i - 1];
    const cur = leftPts[i];
    const ym = (prev[1] + cur[1]) / 2;
    dPath += `Q${prev[0] - 2} ${ym} ${cur[0]} ${cur[1]} `;
  }
  const lastY = startY + length;
  const lastX = cx + dxCurve;
  dPath += `C${lastX - 2} ${lastY + 4} ${lastX - 3} ${lastY + 8} ${lastX} ${lastY + 12} C${lastX + 3} ${lastY + 8} ${lastX + 2} ${lastY + 4} ${rightPts[rightPts.length - 1][0]} ${rightPts[rightPts.length - 1][1]} `;
  for (let i = rightPts.length - 2; i >= 0; i--) {
    const prev = rightPts[i + 1];
    const cur = rightPts[i];
    const ym = (prev[1] + cur[1]) / 2;
    dPath += `Q${prev[0] + 2} ${ym} ${cur[0]} ${cur[1]} `;
  }
  dPath += 'Z';
  strands.push(`M${lastX - 4} ${lastY + 3} L${lastX + 4} ${lastY + 3} M${lastX - 4} ${lastY + 5} L${lastX + 4} ${lastY + 5}`);
  strands.push(`M${lastX - 2} ${lastY + 6} L${lastX - 4} ${lastY + 14} M${lastX} ${lastY + 6} L${lastX} ${lastY + 15} M${lastX + 2} ${lastY + 6} L${lastX + 4} ${lastY + 14}`);
  return { d: dPath, strands, highlights };
}

